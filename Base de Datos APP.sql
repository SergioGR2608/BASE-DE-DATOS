-- PARA CREAR UNA BASE DE DATOS SI NO EXISTE OTRA LLAMADA IGUAL--
CREATE DATABASE IF NOT EXISTS APP_BASE_DE_DATOS;

-- PARA CREAR UNA TABLA --
CREATE TABLE Usuarios(
	-- METER LOS NOMBRES Y TIPOS DE DATOS --
	`idUsuario` tinyint(2) UNSIGNED AUTO_INCREMENT NOT NULL PRIMARY KEY, -- CLAVE PRIMARIA --
	`Nombre` varchar(100) NOT NULL
);

CREATE TABLE Tareas (
	`idTarea` tinyint(2) UNSIGNED AUTO_INCREMENT NOT NULL PRIMARY KEY, -- CLAVE PRIMARIA
	`Tarea` varchar(100) NOT NULL
);

CREATE TABLE Reparto (
	`idTarea` tinyint(2) NOT NULL,
	`idUsuario` tinyint(2) NOT NULL,
	`Fecha` DATE NOT NULL, -- DATE SE USA PARA GUARDAR SIN HORA, POR EJEMPLO: AAAA/MM/DD --
	CONSTRAINT fk_tarea FOREIGN KEY(idTarea) REFERENCES Tareas(idTarea), -- CLAVE FORÁNEA Y SU REFERENCIA --
	CONSTRAINT fk_usuario FOREIGN KEY(idUsuario) REFERENCES Usuarios(idUsuario), -- CLAVE FORÁNEA Y SU REFERENCIA --
	CONSTRAINT pk_Reparto PRIMARY KEY(idTarea, Fecha), -- CLAVE PRIMARIA COMPUESTA --
);

CREATE UNIQUE INDEX csu_Reparto ON Reparto (idTarea, Fecha);

CREATE TABLE ListaDeLaCompra (
	`Objeto` varchar(50) NOT NULL PRIMARY KEY, -- CLAVE PRIMARIA --
	`Cantidad` tinyint(2) NOT NULL
);
