-- PARA CREAR UNA BASE DE DATOS SI NO EXISTE OTRA LLAMADA IGUAL--
CREATE DATABASE IF NOT EXISTS `APP_BASE_DE_DATOS`

-- PARA CREAR UNA TABLA DENTRO DE LA BASE DE DATOS DE ANTES --
USE `APP_BASE_DE_DATOS`
CREATE TABLE Usuarios(
	-- METER LOS NOMBRES Y TIPOS DE DATOS --
	`idUsuario` tinyint(2) NOT NULL PRIMARY KEY, -- CLAVE PRIMARIA --
	`Nombre` varchar(100) NOT NULL,
);

CREATE TABLE Tareas (
	`idTarea` tinyint(2) NOT NULL PRIMARY KEY, -- CLAVE PRIMARIA
	`Tarea` varchar(100) NOT NULL,
);

CREATE TABLE Reparto (
	`idTarea` tinyint(2) NOT NULL,
	`idUsuario` tinyint(2) NOT NULL,
	`Fecha` DATE NOT NULL, -- DATE SE USA PARA GUARDAR SIN HORA, POR EJEMPLO: AAAA/MM/DD --
);
CREATE TABLE ListaDeLaCompra (
	`Objeto` varchar(50) NOT NULL PRIMARY KEY, -- CLAVE PRIMARIA --
	`Cantidad` tinyint(2) NOT NULL,
);
